	if got := MCPToolRef("improvements", "backlog_add"); got != "`testbrand_improvements_backlog_add`" {
		t.Errorf("MCPToolRef(improvements, backlog_add) = %q; want %q", got, "`testbrand_improvements_backlog_add`")
	}
