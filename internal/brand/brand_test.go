func TestCapitalize(t *testing.T) {
	tests := []struct {
		input    string
		expected string
	}{
		{"", ""},
		{"a", "A"},
		{"abc", "Abc"},
		{"ABC", "ABC"},
		{"1abc", "1abc"},
	}

	for _, tc := range tests {
		res := Capitalize(tc.input)
		if res != tc.expected {
			t.Errorf("Capitalize(%q) = %q; want %q", tc.input, res, tc.expected)
		}
	}
}

func TestGlobalDirsAndResolvers(t *testing.T) {
	// Save environment
	origHome := os.Getenv("HOME")
	defer func() { _ = os.Setenv("HOME", origHome) }()

	tempDir, err := os.MkdirTemp("", "brand-test-home")
	if err != nil {
		t.Fatalf("failed to create temp dir: %v", err)
	}
	defer func() { _ = os.RemoveAll(tempDir) }()

	_ = os.Setenv("HOME", tempDir)

	// Restored, unlike every other Brand reassignment in this file, which all defer it.
	// Leaving it set leaks "testbrand2" into every test that runs after this one, and
	// anything deriving a path from Brand then computes it against a brand that does not
	// exist — silently, because the value is still a valid string.
	origBrand := Brand
	defer func() { Brand = origBrand }()
	Brand = "testbrand2"

	expectedGlobalDir := filepath.Join(tempDir, ".testbrand2")
	if GlobalDir() != expectedGlobalDir {
		t.Errorf("GlobalDir() = %q; want %q", GlobalDir(), expectedGlobalDir)
	}

	expectedGlobalRulesDir := filepath.Join(expectedGlobalDir, "rules")
	if GlobalRulesDir() != expectedGlobalRulesDir {
		t.Errorf("GlobalRulesDir() = %q; want %q", GlobalRulesDir(), expectedGlobalRulesDir)
	}

	expectedHubRulesDir := filepath.Join(expectedGlobalDir, "hub", "rules")
	if HubRulesDir() != expectedHubRulesDir {
		t.Errorf("HubRulesDir() = %q; want %q", HubRulesDir(), expectedHubRulesDir)
	}

	res := ResolveModuleRule("mymod", "default-val")
	if res != "default-val" {
		t.Errorf("ResolveModuleRule fallback = %q; want %q", res, "default-val")
	}

	resSkill := ResolveModuleSkill("myskill", "default-skill-val")
	if resSkill != "default-skill-val" {
		t.Errorf("ResolveModuleSkill fallback = %q; want %q", resSkill, "default-skill-val")
	}

	// Now set up local rules dir in current working directory
	wd, err := os.Getwd()
	if err != nil {
		t.Fatalf("failed to get wd: %v", err)
	}

	localRulesDir := filepath.Join(wd, ".testbrand2", "rules")
	err = os.MkdirAll(localRulesDir, 0755)
	if err != nil {
		t.Fatalf("failed to create local rules dir: %v", err)
	}
	defer func() { _ = os.RemoveAll(filepath.Join(wd, ".testbrand2")) }()

	localRuleFile := filepath.Join(localRulesDir, "mymod.md")
	ruleContent := "local-rule-content: {{_TESTBRAND2_DEFAULT_RULE_CONTENT_}}"
	err = os.WriteFile(localRuleFile, []byte(ruleContent), 0644)
	if err != nil {
		t.Fatalf("failed to write local rule: %v", err)
	}

	localSkillFile := filepath.Join(localRulesDir, "myskill_skill.md")
	skillContent := "local-skill-content: {{_TESTBRAND2_DEFAULT_SKILL_CONTENT_}}"
	err = os.WriteFile(localSkillFile, []byte(skillContent), 0644)
	if err != nil {
		t.Fatalf("failed to write local skill: %v", err)
	}

	res = ResolveModuleRule("mymod", "default-val")
	expectedRule := "local-rule-content: default-val"
	if res != expectedRule {
		t.Errorf("ResolveModuleRule local = %q; want %q", res, expectedRule)
	}

	// Test ResolveModuleSkill from local rules dir
	resSkill = ResolveModuleSkill("myskill", "default-skill-val")
	expectedSkill := "local-skill-content: default-skill-val"
	if resSkill != expectedSkill {
		t.Errorf("ResolveModuleSkill local = %q; want %q", resSkill, expectedSkill)
	}

	// Clean up local rules file to test global fallback
	_ = os.RemoveAll(filepath.Join(wd, ".testbrand2"))

	err = os.MkdirAll(expectedGlobalRulesDir, 0755)
	if err != nil {
		t.Fatalf("failed to create global rules dir: %v", err)
	}

	globalRuleFile := filepath.Join(expectedGlobalRulesDir, "mymod.md")
	err = os.WriteFile(globalRuleFile, []byte(ruleContent), 0644)
	if err != nil {
		t.Fatalf("failed to write global rule: %v", err)
	}

	globalSkillFile := filepath.Join(expectedGlobalRulesDir, "myskill_skill.md")
	err = os.WriteFile(globalSkillFile, []byte(skillContent), 0644)
	if err != nil {
		t.Fatalf("failed to write global skill: %v", err)
	}

	res = ResolveModuleRule("mymod", "default-val")
	if res != expectedRule {
		t.Errorf("ResolveModuleRule global = %q; want %q", res, expectedRule)
	}

	// Test ResolveModuleSkill from global rules dir
	resSkill = ResolveModuleSkill("myskill", "default-skill-val")
	if resSkill != expectedSkill {
		t.Errorf("ResolveModuleSkill global = %q; want %q", resSkill, expectedSkill)
	}

	// Clean up global rules to test Hub fallback
	_ = os.RemoveAll(expectedGlobalRulesDir)

	// Set up Hub rules dir (simulates main branch of Hub Git repo)
	err = os.MkdirAll(expectedHubRulesDir, 0755)
	if err != nil {
		t.Fatalf("failed to create hub rules dir: %v", err)
	}

	hubRuleContent := "hub-rule-content: {{_TESTBRAND2_DEFAULT_RULE_CONTENT_}}"
	hubRuleFile := filepath.Join(expectedHubRulesDir, "mymod.md")
	err = os.WriteFile(hubRuleFile, []byte(hubRuleContent), 0644)
	if err != nil {
		t.Fatalf("failed to write hub rule: %v", err)
	}

	hubSkillContent := "hub-skill-content: {{_TESTBRAND2_DEFAULT_SKILL_CONTENT_}}"
	hubSkillFile := filepath.Join(expectedHubRulesDir, "myskill_skill.md")
	err = os.WriteFile(hubSkillFile, []byte(hubSkillContent), 0644)
	if err != nil {
		t.Fatalf("failed to write hub skill: %v", err)
	}

	res = ResolveModuleRule("mymod", "default-val")
	expectedHubRule := "hub-rule-content: default-val"
	if res != expectedHubRule {
		t.Errorf("ResolveModuleRule hub = %q; want %q", res, expectedHubRule)
	}

	// Test ResolveModuleSkill from Hub rules dir
	resSkill = ResolveModuleSkill("myskill", "default-skill-val")
	expectedHubSkill := "hub-skill-content: default-skill-val"
	if resSkill != expectedHubSkill {
		t.Errorf("ResolveModuleSkill hub = %q; want %q", resSkill, expectedHubSkill)
	}

	// Test precedence: global CLI override wins over Hub override
	err = os.MkdirAll(expectedGlobalRulesDir, 0755)
	if err != nil {
		t.Fatalf("failed to re-create global rules dir: %v", err)
	}
	err = os.WriteFile(globalRuleFile, []byte(ruleContent), 0644)
	if err != nil {
		t.Fatalf("failed to re-write global rule: %v", err)
	}
	err = os.WriteFile(globalSkillFile, []byte(skillContent), 0644)
	if err != nil {
		t.Fatalf("failed to re-write global skill: %v", err)
	}

	res = ResolveModuleRule("mymod", "default-val")
	if res != expectedRule {
		t.Errorf("ResolveModuleRule precedence (global > hub) = %q; want %q", res, expectedRule)
	}
	resSkill = ResolveModuleSkill("myskill", "default-skill-val")
	if resSkill != expectedSkill {
		t.Errorf("ResolveModuleSkill precedence (global > hub) = %q; want %q", resSkill, expectedSkill)
	}
}

func TestGlobalDirErr(t *testing.T) {
	// Save environment and clear HOME/USERPROFILE to cause UserHomeDir failure if possible
	origHome := os.Getenv("HOME")
	origUserProfile := os.Getenv("USERPROFILE")
	defer func() {
		_ = os.Setenv("HOME", origHome)
		_ = os.Setenv("USERPROFILE", origUserProfile)
	}()

	_ = os.Unsetenv("HOME")
	_ = os.Unsetenv("USERPROFILE")

	// Verify GlobalDir returns empty string on error
	// Note: on some environments, os.UserHomeDir might still succeed or fail depending on os configuration.
	// But we test the fallback branch safety.
	res := GlobalDir()
	if res == "" {
		// If it did fail, GlobalRulesDir should also return empty
		if GlobalRulesDir() != "" {
			t.Errorf("expected GlobalRulesDir() to be empty when GlobalDir() is empty")
		}
		// HubRulesDir should also return empty when GlobalDir is empty
		if HubRulesDir() != "" {
			t.Errorf("expected HubRulesDir() to be empty when GlobalDir() is empty")
		}
		// RuntimeDir should also return empty when GlobalDir is empty
		if RuntimeDir("v1.0.0") != "" {
			t.Errorf("expected RuntimeDir() to be empty when GlobalDir() is empty")
		}
	}
}

